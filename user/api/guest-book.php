<?php
/**
 * user/api/guest-book.php
 * -----------------------------------------------------------------------
 * POST-only JSON endpoint for guest (no-account) bookings.
 * No session or login is required to submit.
 *
 * Expected multipart/form-data fields:
 *   csrf_token      string   (from bienmarko_csrf_token in the page)
 *   room_id         int      accommodation ID
 *   checkin         YYYY-MM-DD
 *   checkout        YYYY-MM-DD
 *   guests          int      1–50
 *   first_name      string
 *   last_name       string
 *   email           string
 *   phone           string
 *   address         string   (optional)
 *   requests        string   (optional, max 500 chars — stored in notes)
 *   payment_method  cash|gcash
 *
 * Success response:
 * {
 *   "success": true,
 *   "reference": "BM-XXXXXXXX",
 *   "room_name": "Barkada Room",
 *   "checkin": "2026-08-20",
 *   "checkout": "2026-08-22",
 *   "nights": 2,
 *   "total": "1200.00"
 * }
 *
 * Error response:
 * {
 *   "success": false,
 *   "error": "Human-readable message.",
 *   "field_errors": { "field_key": "Per-field message." }   // optional
 * }
 *
 * Tables used:
 *   accommodations      (read)  — confirms room exists + is available
 *   bookings            (read + write)  — conflict detection + insert
 *   admin_notifications (write) — inserts one row so admin panel bell fires
 * -----------------------------------------------------------------------
 */

require_once __DIR__ . '/../../includes/db.php';
require_once __DIR__ . '/../../includes/auth-common.php';

// Guest bookings do NOT require a login, but we start a session so the
// CSRF token generated by guest-book.php (the page) is available here.
bienmarko_start_session();

header('Content-Type: application/json; charset=utf-8');
header('X-Robots-Tag: noindex');

/* ── helpers ──────────────────────────────────────────────────────── */
function gb_fail(int $code, string $msg, array $fieldErrors = []): never
{
    http_response_code($code);
    $body = ['success' => false, 'error' => $msg];
    if ($fieldErrors) {
        $body['field_errors'] = $fieldErrors;
    }
    echo json_encode($body);
    exit;
}

function gb_ok(array $data): never
{
    echo json_encode(['success' => true] + $data);
    exit;
}

/* ── method guard ─────────────────────────────────────────────────── */
if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') {
    gb_fail(405, 'Method not allowed.');
}

/* ── CSRF ─────────────────────────────────────────────────────────── */
if (!bienmarko_csrf_valid($_POST['csrf_token'] ?? null)) {
    gb_fail(403, 'Your session has expired. Please refresh the page and try again.');
}

/* ── DB ───────────────────────────────────────────────────────────── */
try {
    $pdo = bienmarko_db();
} catch (Throwable $e) {
    gb_fail(503, 'Database unavailable. Please try again shortly.');
}

/* ── ensure schema is up to date ─────────────────────────────────── */
// These run silently — if the column/table already exists the statement
// is a no-op (IF NOT EXISTS / MODIFY is safe to re-run on every request).
try {
    // Make guest_id nullable so walk-in guests can book without an account.
    $pdo->exec(
        "ALTER TABLE `bookings`
         MODIFY COLUMN `guest_id` INT UNSIGNED NULL DEFAULT NULL"
    );

    // Add guest-booking columns if missing.
    $pdo->exec(
        "ALTER TABLE `bookings`
             ADD COLUMN IF NOT EXISTS `guest_name`     VARCHAR(200) NULL DEFAULT NULL,
             ADD COLUMN IF NOT EXISTS `email`          VARCHAR(200) NULL DEFAULT NULL,
             ADD COLUMN IF NOT EXISTS `phone`          VARCHAR(30)  NULL DEFAULT NULL,
             ADD COLUMN IF NOT EXISTS `address`        VARCHAR(255) NULL DEFAULT NULL,
             ADD COLUMN IF NOT EXISTS `payment_method` ENUM('cash','gcash') NULL DEFAULT 'cash',
             ADD COLUMN IF NOT EXISTS `booking_type`   ENUM('registered','guest') NOT NULL DEFAULT 'registered'"
    );

    // Ensure admin_notifications table exists.
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS `admin_notifications` (
            `id`         INT UNSIGNED NOT NULL AUTO_INCREMENT,
            `booking_id` INT UNSIGNED NULL DEFAULT NULL,
            `type`       VARCHAR(60)  NOT NULL DEFAULT 'booking',
            `message`    VARCHAR(400) NOT NULL,
            `is_read`    TINYINT(1)   NOT NULL DEFAULT 0,
            `created_at` DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (`id`),
            KEY `idx_booking` (`booking_id`),
            KEY `idx_is_read` (`is_read`)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );

    // Add any columns that may be missing from an older admin_notifications.
    $pdo->exec(
        "ALTER TABLE `admin_notifications`
             ADD COLUMN IF NOT EXISTS `booking_id` INT UNSIGNED NULL DEFAULT NULL,
             ADD COLUMN IF NOT EXISTS `type`       VARCHAR(60) NOT NULL DEFAULT 'booking'"
    );
} catch (Throwable $e) {
    // Log but don't abort — the ALTER may fail if already in the right state
    // on some MySQL versions that don't support ADD COLUMN IF NOT EXISTS.
    // Fall through and let the INSERT fail with a clear error if columns are missing.
    error_log('[bienmarko] guest-book schema migration warning: ' . $e->getMessage());
}

/* ── input harvest & sanitise ────────────────────────────────────── */
$roomId        = filter_var($_POST['room_id']         ?? null, FILTER_VALIDATE_INT);
$checkin       = trim((string) ($_POST['checkin']     ?? ''));
$checkout      = trim((string) ($_POST['checkout']    ?? ''));
$guests        = filter_var($_POST['guests']           ?? null, FILTER_VALIDATE_INT);
$firstName     = trim((string) ($_POST['first_name']  ?? ''));
$lastName      = trim((string) ($_POST['last_name']   ?? ''));
$email         = trim((string) ($_POST['email']       ?? ''));
$phone         = trim((string) ($_POST['phone']       ?? ''));
$address       = trim((string) ($_POST['address']     ?? ''));
$requests      = trim((string) ($_POST['requests']    ?? ''));
$paymentMethod = trim((string) ($_POST['payment_method'] ?? 'cash'));

/* ── field-level validation ──────────────────────────────────────── */
$fieldErrors = [];
$dateRx      = '/^\d{4}-\d{2}-\d{2}$/';
$today       = date('Y-m-d');

if (!$roomId || $roomId < 1) {
    $fieldErrors['room'] = 'Please select an accommodation.';
}

if (!$checkin || !preg_match($dateRx, $checkin)) {
    $fieldErrors['checkin'] = 'Please enter a valid check-in date.';
} elseif ($checkin < $today) {
    $fieldErrors['checkin'] = 'Check-in date cannot be in the past.';
}

if (!$checkout || !preg_match($dateRx, $checkout)) {
    $fieldErrors['checkout'] = 'Please enter a valid check-out date.';
} elseif ($checkin && $checkout <= $checkin) {
    $fieldErrors['checkout'] = 'Check-out must be after check-in.';
}

if (!$guests || $guests < 1 || $guests > 50) {
    $fieldErrors['guests'] = 'Guests must be between 1 and 50.';
}

if ($firstName === '' || mb_strlen($firstName) > 80) {
    $fieldErrors['fname'] = 'First name is required (max 80 characters).';
}

if ($lastName === '' || mb_strlen($lastName) > 80) {
    $fieldErrors['lname'] = 'Last name is required (max 80 characters).';
}

if ($email === '' || !filter_var($email, FILTER_VALIDATE_EMAIL) || mb_strlen($email) > 200) {
    $fieldErrors['email'] = 'Please enter a valid email address.';
}

if ($phone === '' || mb_strlen($phone) < 7 || mb_strlen($phone) > 30) {
    $fieldErrors['phone'] = 'Please enter a valid phone number.';
}

if (mb_strlen($address) > 255) {
    $address = mb_substr($address, 0, 255);
}

if (mb_strlen($requests) > 500) {
    $fieldErrors['requests'] = 'Special requests must be 500 characters or fewer.';
}

if (!in_array($paymentMethod, ['cash', 'gcash'], true)) {
    $paymentMethod = 'cash';
}

if ($fieldErrors) {
    gb_fail(400, 'Please correct the highlighted fields.', $fieldErrors);
}

/* ── confirm room exists and is bookable ─────────────────────────── */
try {
    $roomStmt = $pdo->prepare(
        "SELECT `id`, `name`, `capacity`, `price`, `status`
         FROM `accommodations`
         WHERE `id` = :id
         LIMIT 1"
    );
    $roomStmt->execute(['id' => $roomId]);
    $room = $roomStmt->fetch(PDO::FETCH_ASSOC);
} catch (Throwable $e) {
    error_log('[bienmarko] guest-book room lookup failed: ' . $e->getMessage());
    gb_fail(500, 'Could not verify the selected room. Please try again.');
}

if (!$room) {
    gb_fail(404, 'The selected accommodation does not exist.', ['room' => 'Please select a valid room.']);
}

if (!in_array($room['status'], ['available', 'booked'], true)) {
    gb_fail(409, 'This accommodation is currently unavailable. Please choose another room.', [
        'room' => 'Room is not available for booking.',
    ]);
}

if ($guests > (int) $room['capacity']) {
    gb_fail(400, 'Number of guests exceeds this room\'s capacity of ' . $room['capacity'] . '.', [
        'guests' => 'Maximum capacity is ' . $room['capacity'] . ' guests.',
    ]);
}

/* ── date conflict detection (transaction-safe row-level lock) ────── */
// Overlap condition: existing.check_in < new.check_out AND existing.check_out > new.check_in
try {
    $pdo->beginTransaction();

    $conflictStmt = $pdo->prepare(
        "SELECT COUNT(*) FROM `bookings`
         WHERE `accommodation_id` = :room_id
           AND `status` NOT IN ('cancelled')
           AND `check_in`  < :checkout
           AND `check_out` > :checkin
         FOR UPDATE"
    );
    $conflictStmt->execute([
        'room_id'  => $roomId,
        'checkin'  => $checkin,
        'checkout' => $checkout,
    ]);
    $conflicts = (int) $conflictStmt->fetchColumn();

    if ($conflicts > 0) {
        $pdo->rollBack();
        gb_fail(409,
            'Sorry, this room is already booked for the selected dates. Please choose different dates.',
            ['checkin' => 'These dates conflict with an existing booking.']
        );
    }

    /* ── generate reference number ───────────────────────────────── */
    // BM- + 8 uppercase alphanumeric chars. Retry once on collision.
    $reference = '';
    for ($attempt = 0; $attempt < 2; $attempt++) {
        $candidate = 'BM-' . strtoupper(substr(bin2hex(random_bytes(5)), 0, 8));
        $chkRef    = $pdo->prepare("SELECT COUNT(*) FROM `bookings` WHERE `reference` = :ref FOR UPDATE");
        $chkRef->execute(['ref' => $candidate]);
        if ((int) $chkRef->fetchColumn() === 0) {
            $reference = $candidate;
            break;
        }
    }
    if ($reference === '') {
        $pdo->rollBack();
        gb_fail(500, 'Could not generate a booking reference. Please try again.');
    }

    /* ── compute total ───────────────────────────────────────────── */
    $nights      = (int) round((strtotime($checkout) - strtotime($checkin)) / 86400);
    $totalAmount = round($nights * (float) $room['price'], 2);
    $guestName   = $firstName . ' ' . $lastName;

    /* ── insert booking ──────────────────────────────────────────── */
    // guest_id = NULL  →  walk-in guest booking
    // booking_type = 'guest'
    // Column names match the real bookings table schema exactly.
    $insert = $pdo->prepare(
        "INSERT INTO `bookings`
            (`reference`, `guest_id`, `accommodation_id`,
             `check_in`, `check_out`, `guests_count`,
             `notes`, `status`, `total_amount`,
             `guest_name`, `email`, `phone`, `address`,
             `payment_method`, `booking_type`)
         VALUES
            (:reference, NULL, :accommodation_id,
             :check_in, :check_out, :guests_count,
             :notes, 'confirmed', :total_amount,
             :guest_name, :email, :phone, :address,
             :payment_method, 'guest')"
    );
    $insert->execute([
        'reference'        => $reference,
        'accommodation_id' => $roomId,
        'check_in'         => $checkin,
        'check_out'        => $checkout,
        'guests_count'     => $guests,
        'notes'            => $requests !== '' ? $requests : null,
        'total_amount'     => $totalAmount,
        'guest_name'       => $guestName,
        'email'            => $email,
        'phone'            => $phone,
        'address'          => $address !== '' ? $address : null,
        'payment_method'   => $paymentMethod,
    ]);

    $bookingId = (int) $pdo->lastInsertId();

    /* ── admin notification ──────────────────────────────────────── */
    $ciLabel  = date('M j', strtotime($checkin));
    $coLabel  = date('M j, Y', strtotime($checkout));
    $notifMsg = "New guest booking {$reference}: {$guestName} booked {$room['name']} ({$ciLabel} – {$coLabel})";

    $notifStmt = $pdo->prepare(
        "INSERT INTO `admin_notifications` (`booking_id`, `type`, `message`, `is_read`)
         VALUES (:booking_id, 'booking', :message, 0)"
    );
    $notifStmt->execute([
        'booking_id' => $bookingId,
        'message'    => $notifMsg,
    ]);

    $pdo->commit();

} catch (Throwable $e) {
    if ($pdo->inTransaction()) {
        $pdo->rollBack();
    }
    error_log('[bienmarko] guest-book insert failed: ' . $e->getMessage());
    gb_fail(500, 'Booking could not be saved. Please try again. (' . $e->getMessage() . ')');
}

/* ── success ─────────────────────────────────────────────────────── */
gb_ok([
    'reference' => $reference,
    'room_name' => $room['name'],
    'checkin'   => $checkin,
    'checkout'  => $checkout,
    'nights'    => $nights,
    'total'     => number_format($totalAmount, 2),
]);
